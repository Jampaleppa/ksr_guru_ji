<?php
declare(strict_types=1);
/**
 * scripts/cron_daily_settlement.php
 * ─────────────────────────────────────────────────────────────────
 * CRON: Generate and store the daily settlement report (run at 23:30)
 *
 * Writes into `payment_settlement_reports` (from payment_schema.sql),
 * matching admin/payments/settlement.php.
 *
 * Optional CLI arg: YYYY-MM-DD (defaults to yesterday).
 * ─────────────────────────────────────────────────────────────────
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("CLI only.\n");
}

require_once dirname(__DIR__) . '/payment-core/bootstrap.php';

use KsrPay\AuditLogger;
use KsrPay\AmountCalculator;

/** @var \PDO $pdo */
$pdo = $pdo ?? getDBConnection();

$now        = new DateTimeImmutable();
$targetDate = $argv[1] ?? (new DateTimeImmutable('yesterday'))->format('Y-m-d');
if (!preg_match('/^\d{4}-\d{2}-\d{2}$/', $targetDate)) {
    fwrite(STDERR, "Invalid date argument '{$targetDate}'. Expected YYYY-MM-DD.\n");
    exit(2);
}

$audit = new AuditLogger($pdo);
echo sprintf("[%s] cron_daily_settlement — processing %s\n", $now->format('Y-m-d H:i:s'), $targetDate);

$qs = function (string $sql, array $p) use ($pdo): int {
    $s = $pdo->prepare($sql);
    $s->execute($p);
    return (int)$s->fetchColumn();
};

$collectedPaise = $qs(
    "SELECT COALESCE(SUM(amount_paise),0) FROM payment_transactions
      WHERE status IN ('success','cod_collected') AND DATE(verified_at) = ?",
    [$targetDate]
);
$refundedPaise = $qs(
    "SELECT COALESCE(SUM(amount_paise),0) FROM payment_refunds
      WHERE status = 'completed' AND DATE(completed_at) = ?",
    [$targetDate]
);
$upiCount  = $qs("SELECT COUNT(*) FROM payment_transactions WHERE status IN ('success') AND method='upi' AND DATE(verified_at) = ?", [$targetDate]);
$codCount  = $qs("SELECT COUNT(*) FROM payment_transactions WHERE status IN ('success','cod_collected') AND method='cod' AND DATE(verified_at) = ?", [$targetDate]);
$bankCount = $qs("SELECT COUNT(*) FROM payment_transactions WHERE status IN ('success') AND method='bank_transfer' AND DATE(verified_at) = ?", [$targetDate]);
$netPaise  = $collectedPaise - $refundedPaise;
$totalCount = $upiCount + $codCount + $bankCount;

$driver = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
if ($driver === 'sqlite') {
    $stmt = $pdo->prepare(
        "INSERT OR REPLACE INTO payment_settlement_reports
            (report_date, total_collected_paise, total_refunded_paise, net_paise,
             upi_count, cod_count, bank_transfer_count, generated_at, generated_by, notes)
         VALUES (?, ?, ?, ?, ?, ?, ?, datetime('now'), NULL, ?)"
    );
    $stmt->execute([
        $targetDate, $collectedPaise, $refundedPaise, $netPaise,
        $upiCount, $codCount, $bankCount, 'Generated by cron_daily_settlement.php',
    ]);
} else {
    $stmt = $pdo->prepare(
        "INSERT INTO payment_settlement_reports
            (report_date, total_collected_paise, total_refunded_paise, net_paise,
             upi_count, cod_count, bank_transfer_count, generated_by, notes)
         VALUES (?, ?, ?, ?, ?, ?, ?, NULL, ?)
         ON DUPLICATE KEY UPDATE
            total_collected_paise = VALUES(total_collected_paise),
            total_refunded_paise  = VALUES(total_refunded_paise),
            net_paise             = VALUES(net_paise),
            upi_count             = VALUES(upi_count),
            cod_count             = VALUES(cod_count),
            bank_transfer_count   = VALUES(bank_transfer_count),
            generated_at          = NOW(),
            notes                 = VALUES(notes)"
    );
    $stmt->execute([
        $targetDate, $collectedPaise, $refundedPaise, $netPaise,
        $upiCount, $codCount, $bankCount, 'Generated by cron_daily_settlement.php',
    ]);
}

echo "\n── Settlement Report for {$targetDate} ──────────────────────\n";
echo sprintf("  UPI payments:           %6d\n", $upiCount);
echo sprintf("  COD payments:           %6d\n", $codCount);
echo sprintf("  Bank Transfer payments: %6d\n", $bankCount);
echo sprintf("  Total Collected:        %s\n", AmountCalculator::formatINR($collectedPaise));
echo sprintf("  Total Refunded:         %s\n", AmountCalculator::formatINR($refundedPaise));
echo sprintf("  Net Settlement:         %s\n", AmountCalculator::formatINR($netPaise));

$audit->log(
    eventType: 'DAILY_SETTLEMENT_GENERATED',
    notes:     sprintf(
        "Settlement %s: count=%d (UPI=%d, COD=%d, Bank=%d), collected=%.2f, refunded=%.2f, net=%.2f",
        $targetDate, $totalCount, $upiCount, $codCount, $bankCount,
        $collectedPaise / 100, $refundedPaise / 100, $netPaise / 100
    ),
    actorType: 'system',
    actorId:   0,
);

echo sprintf("\n[%s] cron_daily_settlement complete for %s\n", (new DateTimeImmutable())->format('Y-m-d H:i:s'), $targetDate);
exit(0);
